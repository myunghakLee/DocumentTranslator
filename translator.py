## 사용 예시
if __name__ == "__main__":

    # GOOGLE_API_KEY 환경 변수를 설정해야 합니다.
    # os.environ['GOOGLE_API_KEY'] = 'YOUR_API_KEY' 

    # 'Translator' 클래스의 인스턴스를 생성합니다.
    translator = Translator()

    # 번역할 텍스트 및 언어를 정의합니다.
    korean_text = "To extract high-quality knowledge, previous studies usually increase the size of the teacher model. However, when employing an excessively large teacher model, the performance of the student model may decrease because of the capacity gap. Due to this issue, increasing the size of the teacher model cannot improve the\n-----\n  student model’s performance beyond a certain \n threshold. In other words, there are limitations in the quality of knowledge extracted from the teacher model and transferred to the student model. To address these issues, we propose an Oracle teacher model that extracts high-quality knowledge through the use of reinforced data, generated by XAI."
    source = "English"
    target = "Korean"

    # 번역을 실행합니다.
    translated_text = translator.translate(korean_text, source, target)

    print(f"원본 ({source}): {korean_text}")
    print(f"번역 ({target}): {translated_text}")

    # ---

    ## 클래스 구현 설명

    # 1.  **`__init__(self, model_name)`**:
    #     * `genai.Client()`를 사용하여 **Gemini API 클라이언트**를 초기화합니다. 이 때 `GOOGLE_API_KEY` 환경 변수가 설정되어 있어야 합니다.
    #     * 사용할 모델을 `gemini-2.5-flash`로 기본 설정합니다.

    # 2.  **`translate(self, text, source_language, target_language)`**:
    #     * **프롬프트 엔지니어링**: Gemini 모델에게 번역 역할을 명확히 지시하는 프롬프트를 구성합니다. "오직 번역된 텍스트만 응답"하도록 요청하여 모델의 출력을 단순화합니다.
    #     * **API 호출**: `self.client.models.generate_content` 메서드를 사용하여 Gemini API에 요청을 보냅니다.
    #     * **결과 반환**: 응답에서 번역된 텍스트만 추출하여 반환합니다.

